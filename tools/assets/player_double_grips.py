def _gun(point, profile):
    source, anchor, *axes = FRAMES[profile]
    return frames.transform(point, source, anchor, REST, axes)


def _source(point, profile):
    source, anchor, *axes = FRAMES[profile]
    return frames.transform(point, anchor, source, axes, REST)


def finger_path(start, index, profile):
    """Keep the shared MCP root while seating each phalanx against the stock."""
    if index:
        points = [_source(Vector(p), profile) for p in LOWER[profile][index - 1]]
        points[0] = start - REST[2] * 0.004 if profile == "grubber_sawnoff" and index == 3 else start.copy()
        return points
    controls = [_gun(start, profile), *map(Vector, INDEX[profile])]
    return stock_curve(controls, 14, lambda point: _source(point, profile))


def thumb_path(profile):
    """Rest the thumb alongside the upper wrist without forcing a tip chord."""
    across, along, inward = REST
    start = Vector((-0.649, 0, 1.011)) - across * 0.015 - along * 0.006 + inward * 0.008
    controls = [_gun(start, profile), *map(Vector, THUMB[profile])]
    return stock_curve(controls, 10, lambda point: _source(point, profile))
